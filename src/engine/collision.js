function pointInPoly(px, py, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > py) !== (yj > py) && px < (xj - xi) * (py - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function distToSegment2(px, py, [ax, ay], [bx, by]) {
  const dx = bx - ax, dy = by - ay, len = dx * dx + dy * dy;
  const t = len ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len)) : 0;
  const qx = ax + t * dx - px, qy = ay + t * dy - py;
  return qx * qx + qy * qy;
}

// Does a circle at world (x, y) with radius r overlap any solid collision polygon?
export function blocked(map, x, y, r) {
  if (x - r < 0 || y - r < 0 || x + r >= map.W * 100 || y + r >= map.H * 100) return true;
  const c0 = Math.floor((x - r) / 100), c1 = Math.floor((x + r) / 100), r0 = Math.floor((y - r) / 100), r1 = Math.floor((y + r) / 100);
  for (let cy = r0; cy <= r1; cy++) for (let cx = c0; cx <= c1; cx++) {
    const v = map.collision[cy * map.W + cx];
    if (!v) continue;
    const shape = COLLISION_SHAPES[v];
    if (!shape) return true;                 // out-of-table values (255) treated as solid
    const poly = shape.map(([px, py]) => [cx * 100 + px, cy * 100 + py]);
    if (pointInPoly(x, y, poly)) return true;
    for (let i = 0; i < poly.length; i++) if (distToSegment2(x, y, poly[i], poly[(i + 1) % poly.length]) < r * r) return true;
  }
  return false;
}

// Move with per-axis sliding. Returns the new position.
export function moveWithCollision(map, x, y, dx, dy, r) {
  if (!blocked(map, x + dx, y + dy, r)) return [x + dx, y + dy];
  if (dx && !blocked(map, x + dx, y, r)) return [x + dx, y];
  if (dy && !blocked(map, x, y + dy, r)) return [x, y + dy];
  return [x, y];
}
